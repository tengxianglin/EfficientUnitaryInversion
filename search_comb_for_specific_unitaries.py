"""
Searches for comb structures to implement unitary transformations generated by specific Hamiltonian Pauli terms.

Adjust the following constants to configure the search:
  - TARGET_FUNC        : target transformation function (e.g., conj, dagger)
  - PAULI_SUPPORTS     : list of Pauli-term configurations to explore
  - MAX_ATTEMPTS       : maximum attempts per configuration
  - SLOTS              : number or [min, max] range of time slots
  - PARALLELS          : number or [min, max] range of parallel gates
  - ANCILLA            : number of ancilla qubits
  - NUM_TRAIN_SET      : size of the training dataset
  - NUM_TEST_SET       : size of the testing dataset

Usage examples:
  - Enable GPU (optional): qk.set_device("cuda:0")
  - Set numeric precision:  qk.set_dtype("complex128")
"""

from tabnanny import verbose
from typing import List

import quairkit as qk
from quairkit.qinfo import dagger
from torch import conj

from utils.hamiltonian_utils import HamiltonianPQCombNet, generate_random_pauli

# qk.set_device("cuda:0")
qk.set_dtype("complex128")
TARGET_FUNC = conj
PAULI_SUPPORTS: List[List[str]] = [
    ["Y0", "Y1", "Y0,Y1"],
    ["Y0", "Y1", "Y2", "Y0,Y1,Y2"],
    ["Y0", "Y1", "Y1,Y2", "Y0,Y2"],
    ["Z0", "Z1", "Z2", "Z0,Z1", "Z0,Z2", "Z1,Z2", "Z0,Z1,Z2"],
]
MAX_ATTEMPTS = 5  # Maximum attempts to find a solution
SLOTS = [1, 3]  # Range or number of slots to search for solutions
PARALLELS = [1, 2]  # Range or number of parallel gates to search for solutions
ANCILLA = 1  # Range or number of ancilla qubits to search for solutions
NUM_TRAIN_SET = 1000  # Number of training data sets
NUM_TEST_SET = 1000  # Number of test data sets



def run_search():

    searcher = HamiltonianPQCombNet(
        target_func=TARGET_FUNC,  # Target function to apply, e.g., conj, dagger, transpose
        task_name="example_search",  # Name of the subdirectory for saving results
        fidelity_threshold=0.999,  # Fidelity threshold for the search
        num_train_set=NUM_TRAIN_SET,  # Number of training data sets
        num_test_set= NUM_TEST_SET,  # Number of test data sets
        save_dir=f"search_results_{TARGET_FUNC.__name__}_for_specific_unitaries",  # Name of the root directory
    )
    results = searcher.search_from_list(
        pauli_supports=PAULI_SUPPORTS,
        slots=SLOTS,  # [min_slots, max_slots] or a single slot number
        parallels=PARALLELS,  # [min_parallels, max_parallels] or a single parallel number
        ancilla=ANCILLA,  # [min_ancilla, max_ancilla] or a single ancilla number
        max_attempts=MAX_ATTEMPTS,  # Maximum attempts to find a solution
        # verbose=True,  # Enable verbose output
    )
    for result in results:
        pauli_support = result.get("pauli_support", [])
        num_slots = result.get("num_slots", -1)
        num_parallels = result.get("num_parallels", -1)
        ancilla = result.get("ancilla", -1)
        if num_slots > 0 and num_parallels > 0 and ancilla >= 0:
            print(
                f"unitaries generated from {pauli_support} can be implemented with "
                f"{num_slots} slots, {num_parallels} parallels, {ancilla} ancilla qubits "
                f"for {TARGET_FUNC.__name__}"
            )
        else:
            print(
                f"unitaries generated from {pauli_support} cannot be implemented "
                f"for {TARGET_FUNC.__name__} with the specified slots, parallels, and ancilla qubits."
            )


if __name__ == "__main__":
    run_search()
